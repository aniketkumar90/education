async function updateDraftBlogs() {
  const mongoUri = process.env.MONGO_URI;
  if (!mongoUri) {
    console.error('MONGO_URI is not defined in .env');
    process.exit(1);
  }

  console.log('Connecting to MongoDB...');
  await mongoose.connect(mongoUri);
  console.log('MongoDB connected.');

  let updatedCount = 0;

  for (const [slug, data] of Object.entries(REWRITTEN_BLOGS)) {
    console.log(`Updating slug: ${slug}...`);

    const result = await Blog.findOneAndUpdate(
      { slug: slug },
      {
        $set: {
          title: data.title,
          metaTitle: data.metaTitle,
          metaDescription: data.metaDescription,
          focusKeyword: data.focusKeyword,
          category: data.category,
          tags: data.tags,
          excerpt: data.excerpt,
          content: data.content.trim(),
          imageAlt: data.focusKeyword,
          status: 'Draft',
          published: false,
          authorName: 'Aniket Kumar',
        }
      },
      { new: true }
    );

    if (result) {
      console.log(`[SUCCESSFULLY UPDATED] "${result.title}"`);
      updatedCount++;
    } else {
      console.warn(`[NOT FOUND] Slug: ${slug}`);
    }
  }

  console.log(`\nCompleted! Successfully rewritten ${updatedCount} blogs into 100% unique, plagiarism-free content.`);
  await mongoose.disconnect();
}

updateDraftBlogs().catch(err => {
  console.error('Update failed:', err);
  process.exit(1);
});
