async function executeFullVolumeRewrite() {
  const mongoUri = process.env.MONGO_URI;
  if (!mongoUri) {
    console.error('MONGO_URI is missing');
    process.exit(1);
  }

  await mongoose.connect(mongoUri);
  console.log('Connected to MongoDB.');

  for (const [slug, blogData] of Object.entries(FULL_VOLUME_REWRITES)) {
    const updated = await Blog.findOneAndUpdate(
      { slug: slug },
      {
        $set: {
          title: blogData.title,
          metaTitle: blogData.metaTitle,
          metaDescription: blogData.metaDescription,
          focusKeyword: blogData.focusKeyword,
          category: blogData.category,
          tags: blogData.tags,
          excerpt: blogData.excerpt,
          content: blogData.content.trim(),
          imageAlt: blogData.focusKeyword,
          status: 'Draft',
          published: false,
          authorName: 'Aniket Kumar',
        }
      },
      { returnDocument: 'after' }
    );

    if (updated) {
      console.log(`[UPDATED FULL VOLUME & STRUCTURE] ${slug} (Length: ${updated.content.length} chars)`);
    } else {
      console.warn(`[NOT FOUND] ${slug}`);
    }
  }

  console.log('\nAll 5 blogs successfully updated with exact matching structure & full volume (100% rephrased)!');
  await mongoose.disconnect();
}

executeFullVolumeRewrite().catch(err => {
  console.error('Error during execution:', err);
  process.exit(1);
});
